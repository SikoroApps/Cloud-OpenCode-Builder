import { test } from "node:test";
import assert from "node:assert/strict";
import {
  createImageGenerationService,
  ImageServiceError,
  validateImageUpload,
} from "../src/images.ts";
import { pngBytes } from "./phase6-8-helpers.ts";

test("image generation calls the fixed free provider URL and validates the returned image", async () => {
  let requestedUrl = "";
  const service = createImageGenerationService({
    baseUrl: "https://image.example.invalid/prompt",
    fetchImpl: async (input) => {
      requestedUrl = String(input);
      return new Response(pngBytes(), { status: 200, headers: { "content-type": "image/png" } });
    },
  });

  const generated = await service.generate({ prompt: "a friendly robot icon", size: 512 });
  assert.equal(generated.mimeType, "image/png");
  assert.deepEqual(generated.bytes, pngBytes());
  const parsed = new URL(requestedUrl);
  assert.equal(parsed.origin, "https://image.example.invalid");
  assert.equal(parsed.pathname, "/prompt/a%20friendly%20robot%20icon");
  assert.equal(parsed.searchParams.get("width"), "512");
  assert.equal(parsed.searchParams.get("height"), "512");
  assert.equal(parsed.searchParams.get("nologo"), "true");
});

test("image generation rejects provider failures and non-image responses", async () => {
  const failed = createImageGenerationService({
    fetchImpl: async () => new Response("upstream down", { status: 503 }),
  });
  await assert.rejects(
    () => failed.generate({ prompt: "a robot", size: 512 }),
    (error: unknown) => error instanceof ImageServiceError && error.code === "image_generation_failed",
  );

  const html = createImageGenerationService({
    fetchImpl: async () => new Response("<html>not an image</html>", {
      status: 200,
      headers: { "content-type": "text/html" },
    }),
  });
  await assert.rejects(
    () => html.generate({ prompt: "a robot", size: 512 }),
    (error: unknown) => error instanceof ImageServiceError && error.code === "image_generation_failed",
  );

  const invalidSize = createImageGenerationService({
    fetchImpl: async () => new Response(pngBytes(), { status: 200, headers: { "content-type": "image/png" } }),
  });
  await assert.rejects(
    () => invalidSize.generate({ prompt: "a robot", size: 64 as any }),
    (error: unknown) => error instanceof ImageServiceError && error.code === "invalid_image_size",
  );
});

test("generated bytes pass the same upload validation used for user images", () => {
  const validated = validateImageUpload({
    mimeType: "image/png",
    dataBase64: pngBytes().toString("base64"),
    filename: "generated.png",
  });
  assert.equal(validated.mimeType, "image/png");
  assert.equal(validated.sizeBytes, pngBytes().length);
  assert.equal(validated.sha256.length, 64);
});
